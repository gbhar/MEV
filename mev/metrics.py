from prometheus_client import Counter, Gauge, Histogram

blocks_processed = Counter("blocks_processed_total", "Blocks the loop has processed")
blocks_skipped = Counter("blocks_skipped_total", "Blocks never processed (catch-up cap or retries exhausted)")
rpc_errors = Counter("rpc_errors_total", "Failed RPC calls (head poll, block header or pool state)")
rpc_latency = Histogram("rpc_latency_seconds", "Latency of fetching one block's pool states")
opportunities_detected = Counter("opportunities_detected_total", "Candidates whose spread cleared the fee floor")
simulations = Counter("simulations_total", "Trade-size simulations run")
profitable_simulations = Counter("profitable_simulations_total", "Simulations with net > 0")
risk_blocks = Counter("risk_blocks_total", "Candidates blocked by the risk engine", ["rule"])
paper_trades = Counter("paper_trades_total", "Paper trades opened")
paper_profit_usd = Gauge("paper_profit_usd", "Cumulative realized paper net profit (USD), sum of paper_trades.realized_net_usd")
paper_resolve_lag = Histogram("paper_resolve_lag_blocks", "resolved_block - opened_block per paper trade", buckets=(1, 2, 3, 5, 10))
pool_price = Gauge("pool_price", "Marginal price token1/token0", ["pool_id"])
spread_bps = Gauge("spread_bps", "Best spread seen on the last block", ["buy_pool", "sell_pool"])
events_fetched = Counter("events_fetched_total", "Pool logs decoded, by event type", ["event_type"])
events_applied = Counter("events_applied_total", "Pool events whose end-of-block state agreed with the fetched state", ["pool_id"])
state_divergence = Counter("state_divergence_total", "Blocks where event-derived state disagreed with fetched state", ["pool_id"])
log_fetch_errors = Counter("log_fetch_errors_total", "eth_getLogs failures (the block continues without events)")
reorgs = Counter("reorgs_total", "Blocks whose parentHash did not match the stored hash of block-1")
paper_trades_resolved = Counter("paper_trades_resolved_total", "Paper trades resolved", ["still_profitable"])
scanner_latency = Histogram("scanner_latency_seconds", "scan() wall time per block")
simulation_latency = Histogram("simulation_latency_seconds", "simulate() wall time per candidate")
feature_latency = Histogram("feature_latency_seconds", "feature vector computation per opportunity")
pools_refetched = Histogram("pools_refetched_per_block", "Pools whose state was fetched (not carried forward) per block", buckets=(0, 1, 2, 5, 10, 20, 50, 100))
executions = Counter("executions_total", "FlashArb transactions built by the execution engine", ["mode", "status"])
live_profit_usd = Gauge("live_profit_usd", "Cumulative realized live net profit (USD), sum of executions.realized_usd where mode=live")
execution_latency = Histogram("execution_latency_seconds", "Build + eth_call (+ send) wall time per execution")
