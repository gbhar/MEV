"""Regenerate FLASH_ARB in mev/chain/abi.py from the forge artifact (run after `make contract-build`)."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
art = json.loads((ROOT / "contracts/out/FlashArb.sol/FlashArb.json").read_text())
keep = {"execute", "owner", "paused", "setPaused", "setOwner", "rescue", "aave", "morpho"}
abi = [e for e in art["abi"] if e["type"] in ("event", "error") or (e["type"] == "function" and e["name"] in keep)]
p = ROOT / "mev/chain/abi.py"
s = p.read_text()
block = "FLASH_ARB = " + json.dumps(abi, indent=1).replace("true", "True").replace("false", "False") + "\n"
s = re.sub(r"FLASH_ARB = \[.*\]\n", block, s, flags=re.S)
p.write_text(s)
print(f"FLASH_ARB: {len(abi)} entries")

# Runtime bytecode + immutable slots for the virtual (state-override) shadow mode, see mev/execution/virtual.py
dep = art["deployedBytecode"]
refs = dep["immutableReferences"]
order = sorted(refs, key=int)   # AST ids ascend in declaration order: aave, then morpho
code_py = ROOT / "mev/chain/flash_arb_code.py"
code_py.write_text(
    '"""FlashArb runtime bytecode as compiled (contracts/out), with its two immutables (aave, morpho) still zero;\n'
    'mev/execution/virtual.py patches them in. Generated by scripts/gen_abi.py; do not edit by hand."""\n'
    f'DEPLOYED_CODE = "{dep["object"]}"\n'
    f'IMMUTABLE_OFFSETS = {{"aave": {[r["start"] for r in refs[order[0]]]}, "morpho": {[r["start"] for r in refs[order[1]]]}}}\n'
    'OWNER_SLOT = 0   # address owner (bytes 0-19) and bool paused (byte 20) share slot 0; see `forge inspect FlashArb storage-layout`\n')
print(f"flash_arb_code.py: {(len(dep['object']) - 2) // 2} bytes of code, immutables at {len(refs[order[0]])}+{len(refs[order[1]])} offsets")
